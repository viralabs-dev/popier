//! `popier init --discover`: finds the repositories the user can see through
//! their GitHub token (the one `gh` is logged in with) and writes a config.

use std::collections::BTreeMap;

use anyhow::Result;
use futures::StreamExt;

use crate::config::SAMPLE;
use crate::github::{Client, RepoDto};

/// How many repositories are checked for workflows at the same time.
const CONCURRENCY: usize = 8;

/// A repository worth watching: not archived, not a fork, with active workflows.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Found {
    pub owner: String,
    pub name: String,
}

impl Found {
    pub fn slug(&self) -> String {
        format!("{}/{}", self.owner, self.name)
    }
}

/// What discovery saw, so the caller can explain the result.
#[derive(Debug, Default)]
pub struct Report {
    pub found: Vec<Found>,
    pub seen: usize,
    pub skipped_archived_or_fork: usize,
    pub without_workflows: usize,
}

/// Lists the user's repositories, keeping only `owners` when it is not empty.
pub async fn discover(client: &Client, owners: &[String]) -> Result<Report> {
    let repos: Vec<RepoDto> = client
        .list_user_repos()
        .await?
        .into_iter()
        .filter(|r| {
            owners.is_empty()
                || owners
                    .iter()
                    .any(|o| o.eq_ignore_ascii_case(&r.owner.login))
        })
        .collect();
    // Counted after the owner filter, so `--owner x` reports x's repos only.
    let mut report = Report {
        seen: repos.len(),
        ..Report::default()
    };
    let wanted: Vec<RepoDto> = repos
        .into_iter()
        .filter(|r| {
            let keep = !r.archived && !r.fork && !r.disabled;
            if !keep {
                report.skipped_archived_or_fork += 1;
            }
            keep
        })
        .collect();

    let checked: Vec<(RepoDto, bool)> = futures::stream::iter(wanted)
        .map(|repo| async move {
            // A repo with Actions turned off answers 404; treat it as having none.
            let active = client
                .list_workflows(&repo.full_name)
                .await
                .map(|wfs| {
                    wfs.iter()
                        .any(|w| w.state.as_deref().is_none_or(|s| s == "active"))
                })
                .unwrap_or(false);
            (repo, active)
        })
        .buffered(CONCURRENCY)
        .collect()
        .await;

    for (repo, active) in checked {
        if active {
            report.found.push(Found {
                owner: repo.owner.login,
                name: repo.name,
            });
        } else {
            report.without_workflows += 1;
        }
    }
    report.found.sort_by_key(|a| a.slug().to_lowercase());
    Ok(report)
}

/// Project prefix of a repo name: `brabo-api` → `brabo`.
fn prefix(name: &str) -> &str {
    name.split(['-', '_', '.']).next().unwrap_or(name)
}

/// Groups repos of one owner that share a name prefix (`brabo`, `brabo-api`,
/// `brabo-web`, ...). Returns the groups, then the repos left on their own.
pub fn suggest_groups(found: &[Found]) -> (Vec<(String, Vec<Found>)>, Vec<Found>) {
    let mut by_key: BTreeMap<(String, String), Vec<Found>> = BTreeMap::new();
    for repo in found {
        let key = (repo.owner.clone(), prefix(&repo.name).to_lowercase());
        by_key.entry(key).or_default().push(repo.clone());
    }

    // The same prefix under two owners would give two groups with one name.
    let mut prefix_owners: BTreeMap<String, usize> = BTreeMap::new();
    for ((_, p), members) in &by_key {
        if members.len() > 1 {
            *prefix_owners.entry(p.clone()).or_default() += 1;
        }
    }

    let mut groups = Vec::new();
    let mut singles = Vec::new();
    for ((owner, p), mut members) in by_key {
        if members.len() < 2 {
            singles.extend(members);
            continue;
        }
        // The repo named exactly like the project goes first.
        members.sort_by_key(|m| (m.name.to_lowercase() != p, m.name.to_lowercase()));
        let name = if prefix_owners[&p] > 1 {
            format!("{owner}/{p}")
        } else {
            p
        };
        groups.push((name, members));
    }
    singles.sort_by_key(|a| a.slug().to_lowercase());
    (groups, singles)
}

/// Config text: the sample's `[settings]`, then groups, then loose repos.
pub fn render(found: &[Found]) -> String {
    let (groups, singles) = suggest_groups(found);
    // Repo names are unique within an owner; use them as labels unless two
    // owners share one.
    let ambiguous = |name: &str| found.iter().filter(|f| f.name == name).count() > 1;

    let settings_end = SAMPLE.find("# One [[repo]] block").unwrap_or(SAMPLE.len());
    let mut out = String::new();
    out.push_str(SAMPLE[..settings_end].trim_end());
    out.push_str(
        "\n\n# Generated by `popier init --discover`: repositories you can see that are\n\
         # not archived or forks and have active workflows. Edit freely.\n\
         # A [[group]] shows its repos under one row (a project with many repos).\n",
    );

    let repo_block = |out: &mut String, f: &Found| {
        out.push_str(&format!("\n[[repo]]\nslug = {}\n", quote(&f.slug())));
        if !ambiguous(&f.name) {
            out.push_str(&format!("label = {}\n", quote(&f.name)));
        }
    };

    for (name, members) in &groups {
        out.push_str(&format!("\n[[group]]\nname = {}\nrepos = [\n", quote(name)));
        for m in members {
            out.push_str(&format!("    {},\n", quote(&m.slug())));
        }
        out.push_str("]\n");
        for m in members {
            repo_block(&mut out, m);
        }
    }
    for f in &singles {
        repo_block(&mut out, f);
    }
    out
}

fn quote(s: &str) -> String {
    toml::Value::String(s.to_owned()).to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::Config;

    fn f(owner: &str, name: &str) -> Found {
        Found {
            owner: owner.into(),
            name: name.into(),
        }
    }

    #[test]
    fn groups_by_prefix_within_owner() {
        let found = vec![
            f("v", "brabo-api"),
            f("v", "brabo"),
            f("v", "brabo-web"),
            f("v", "popier"),
            f("me", "dotfiles"),
        ];
        let (groups, singles) = suggest_groups(&found);
        assert_eq!(groups.len(), 1);
        assert_eq!(groups[0].0, "brabo");
        let names: Vec<&str> = groups[0].1.iter().map(|m| m.name.as_str()).collect();
        assert_eq!(names, vec!["brabo", "brabo-api", "brabo-web"]);
        let singles: Vec<String> = singles.iter().map(Found::slug).collect();
        assert_eq!(singles, vec!["me/dotfiles", "v/popier"]);
    }

    #[test]
    fn same_prefix_under_two_owners_gets_owner_in_name() {
        let found = vec![f("a", "x-1"), f("a", "x-2"), f("b", "x-1"), f("b", "x-2")];
        let (groups, _) = suggest_groups(&found);
        let names: Vec<&str> = groups.iter().map(|g| g.0.as_str()).collect();
        assert_eq!(names, vec!["a/x", "b/x"]);
    }

    #[test]
    fn rendered_config_parses() {
        let found = vec![
            f("v", "brabo"),
            f("v", "brabo-api"),
            f("v", "popier"),
            f("me", "popier"),
        ];
        let text = render(&found);
        let config = Config::parse(&text).unwrap();
        assert_eq!(config.groups.len(), 1);
        assert_eq!(config.repos.len(), 4);
        assert_eq!(config.repos[0].display_name(), "brabo");
        // "popier" exists under two owners, so it keeps the full slug.
        assert!(config.repos.iter().any(|r| r.display_name() == "me/popier"));
        assert_eq!(config.settings.refresh_secs, 60);
    }
}
